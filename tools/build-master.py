def build_host(stock):
    if firmware.sha(stock) != firmware.STOCK_SHA:
        raise ValueError('Requires the exact original Z7II C 1.70 master')

    patched = bytearray(stock[:-2])
    edits = []
    for offset, replacement in PATCHES:
        original = stock[offset:offset + len(replacement)]
        patched[offset:offset + len(replacement)] = replacement
        edits.append(dict(offset=hex(offset), size=len(replacement),
                          original_sha256=firmware.sha(original)))

    patched.extend(HOST_CODE)
    patched.extend(binascii.crc_hqx(patched, 0).to_bytes(2, 'big'))
    if firmware.sha(patched) != firmware.VERIFIED_MASTER_SHA:
        raise ValueError('Patched master differs from the verified release')

    report = dict(stock_sha256=firmware.sha(stock), master_sha256=firmware.sha(patched),
                  host_bytes=len(HOST_CODE), patches=edits, build_method='binary_patch',
                  anchor='0xb18aedb8', append=hex(firmware.APPEND),
                  camera_verified=False)
    return bytes(patched), report


if __name__ == '__main__':
    firmware.main(host_builder=build_host)
